from langchain_core.prompts import ChatPromptTemplate
from langchain_core.output_parsers import JsonOutputParser
from models import llm

classifier_prompt = ChatPromptTemplate.from_template("""
Ти — класифікатор запитів для українського історичного асистента.

Твоє завдання — визначити, чи стосується запит історії.

Доступні категорії:

1. "історичний" — запит стосується історичних осіб,
   подій, дат, організацій, держав, процесів,
   історичних причин або наслідків.

2. "загальний" — будь-який запит, який не потребує
   пошуку в історичній базі знань:
   привітання, подяка, знайомство, запитання про асистента,
   загальні знання, повсякденні теми тощо.

Приклади:

Запит: Хто такий Сталін?
Відповідь: {{"answer": "історичний"}}

Запит: Розкажи про себе
Відповідь: {{"answer": "загальний"}}

Запит: Коли почалася Друга світова війна?
Відповідь: {{"answer": "історичний"}}

Запит: Привіт!
Відповідь: {{"answer": "загальний"}}

Запит: Дякую за відповідь
Відповідь: {{"answer": "загальний"}}

Запит: Чому розпався СРСР?
Відповідь: {{"answer": "історичний"}}

Запит: Які в тебе можливості?
Відповідь: {{"answer": "загальний"}}

Запит: {query}

Поверни виключно JSON такого формату:
{{"answer": "історичний"}}
або
{{"answer": "загальний"}}
""")

classifier_chain = (
    classifier_prompt
    | llm
    | JsonOutputParser()
)
